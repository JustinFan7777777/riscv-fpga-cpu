// =============================================================================
// Module      : ImmGen.v
// Description : Immediate Generator for RISC-V RV32I
// =============================================================================
//
// ================================ 中文说明 ================================
// 【功能】从 32-bit 指令码中提取立即数并做符号扩展/高位补零，输出 32-bit 结果。
//
// 【在 CPU 数据通路中的位置】
//   指令码 (来自Ifetch的输出inst) ──▶ ImmGen ──▶ MUX(ALUSrc) ──▶ ALU B端口
//   ImmGen 的输出可能作为: ALU的第二个操作数(I-type)、存储偏移(S-type)、
//   分支偏移(B-type)、PC+imm(JAL/JALR)、或高位立即数(LUI/AUIPC)。
//
// 【RISC-V 六种立即数格式 (名字对应其所在指令类型)】
//   类型  | 指令举例  | 立即数在 inst 中的位分布
//   I-type | ADDI, LW  | inst[31:20] → 符号扩展到32bit
//   S-type | SW        | inst[31:25]拼接inst[11:7] → 符号扩展
//   B-type | BEQ       | inst[31]|inst[7]|inst[30:25]|inst[11:8] 末尾补0 → 符号扩展
//   U-type | LUI       | inst[31:12] 左移12位 (低12位补0)
//   J-type | JAL       | inst[31]|inst[19:12]|inst[20]|inst[30:21] 末尾补0 → 符号扩展
//   I-jump | JALR      | inst[31:20] → 符号扩展 (与I-type相同)
//
//   注意: B-type和J-type的立即数最低位总是0(16-bit对齐), 所以硬件编码时省略了bit0.
//         ImmGen会自动在末尾补0.
//
// 【输入】
//   inst[31:0] — 当前正在译码的 32-bit RISC-V 指令
//
// 【输出】
//   Imm[31:0] — 32-bit 立即数 (已符号扩展或补零)
// =============================================================================
`timescale 1ns / 1ps

module ImmGen (
    input  [31:0] inst,     // 32-bit 指令码
    output [31:0] Imm       // 32-bit 立即数输出
);

    reg [31:0] imm_reg;

    // 根据 opcode[6:0] 判断立即数格式, 从32-bit指令中提取并符号扩展到32-bit
    always @(*) begin
        case (inst[6:0])
            // ================================================================
            // I-type: ADDI, LW, JALR 等
            // 指令布局: inst[31:20] = 12-bit 有符号立即数
            // 输出: {{20{符号位}}, 12-bit立即数} → 共12+20=32bit
            // 注: SLLI/SRLI/SRAI 的移位量在低5位 inst[24:20], inst[31:25] 为 funct7,
            //     ImmGen 将它们整体当作立即数输出; ALU 使用 B[4:0] 自动忽略高位, 不受影响
            // ================================================================
            7'b0010011,   // I-type ALU (ADDI/SLLI/ANDI/ORI/XORI/SLTI 等)
            7'b0000011,   // I-type load (LW/LH/LB 等)
            7'b1100111:   // I-type jump (JALR)
                imm_reg = {{20{inst[31]}}, inst[31:20]};

            // ================================================================
            // S-type: SW, SH, SB
            // 指令布局: inst[31:25]=imm[11:5], inst[11:7]=imm[4:0]
            // 输出: {{20{符号位}}, imm[11:5], imm[4:0]} → 共20+7+5=32bit
            // ================================================================
            7'b0100011:
                imm_reg = {{20{inst[31]}}, inst[31:25], inst[11:7]};

            // ================================================================
            // B-type: BEQ, BNE, BLT, BGE, BLTU, BGEU
            // 硬件编码 (RISC-V 为节省引脚重排了立即数位):
            //   inst[31]   = imm[12]    (符号位)
            //   inst[7]    = imm[11]
            //   inst[30:25] = imm[10:5]
            //   inst[11:8]  = imm[4:1]
            //   imm[0]     = 0          (分支目标总是2字节对齐, LSB恒为0)
            // 输出: {{19{符号位}}, imm[12], imm[11], imm[10:5], imm[4:1], 0}
            //      = 19 + 1 + 1 + 6 + 4 + 1 = 32bit
            // ================================================================
            7'b1100011:
                imm_reg = {{19{inst[31]}}, inst[31], inst[7], inst[30:25], inst[11:8], 1'b0};

            // ================================================================
            // U-type: LUI, AUIPC
            // 指令布局: inst[31:12] = 20-bit 立即数 (高位)
            // 输出: {20-bit立即数, 12'b0} → 低12位补零, 无需符号扩展
            // 例: lui x10, 0x12345 → inst[31:12]=0x12345 → imm=0x12345000
            // ================================================================
            7'b0110111,   // LUI
            7'b0010111:   // AUIPC
                imm_reg = {inst[31:12], 12'b0};

            // ================================================================
            // J-type: JAL
            // 硬件编码 (RISC-V 重排):
            //   inst[31]    = imm[20]    (符号位)
            //   inst[19:12] = imm[19:12]
            //   inst[20]    = imm[11]
            //   inst[30:21] = imm[10:1]
            //   imm[0]      = 0          (跳转目标2字节对齐)
            // 输出: {{11{符号位}}, imm[20], imm[19:12], imm[11], imm[10:1], 0}
            //      = 11 + 1 + 8 + 1 + 10 + 1 = 32bit
            // ================================================================
            7'b1101111:
                imm_reg = {{11{inst[31]}}, inst[31], inst[19:12], inst[20], inst[30:21], 1'b0};

            // 非上述 opcode: 回退为 I-type 格式 (安全默认值)
            default:
                imm_reg = {{20{inst[31]}}, inst[31:20]};
        endcase
    end

    assign Imm = imm_reg;

endmodule
