# ==============================================================================
# soft_mul.asm — 软件乘法子程序 (移位相加算法)
# ==============================================================================
# 背景: RV32I 无硬件乘法指令, 但可以用移位+加法在软件中实现乘法。
#       本文件提供通用的32-bit有符号乘法子程序, 作为软硬件协同的示例。
#
# 算法: 逐位检查乘数, 若该位为1则累加被乘数, 被乘数每轮左移, 乘数右移。
#       复杂度 O(n), n=32, 最坏约 200 条指令/次。
#
# 用法: 加载 a0=被乘数, a1=乘数 → jal ra, multiply → a0=结果(低32位)
#       或  加载 a0, a1 → jal ra, multiply_signed → a0=有符号结果
# ==============================================================================

.text
.globl multiply
.globl multiply_signed
.globl _start

# ==============================================================================
# multiply — 32-bit 无符号乘法 (a0 × a1 → a0)
# ==============================================================================
# 输入: a0 = 被乘数 (multiplicand)
#       a1 = 乘数 (multiplier)
# 输出: a0 = 乘积低 32 位
# 破坏: t0, t1, t2
# ==============================================================================
multiply:
    li   t0, 0               # t0 = 累加器 (积)
    li   t2, 32              # t2 = 循环计数 (最多32次)

mul_loop:
    andi t1, a1, 1           # t1 = 乘数最低位 (0或1)
    beqz t1, mul_skip        # 若该位=0, 跳过累加
    add  t0, t0, a0          # 若该位=1, 累加被乘数

mul_skip:
    slli a0, a0, 1           # 被乘数左移 1 位 (×2)
    srli a1, a1, 1           # 乘数右移 1 位 (÷2, 检查下一位)
    addi t2, t2, -1          # 循环计数 -1
    bnez t2, mul_loop        # 继续直到 32 位检查完毕

    mv   a0, t0              # 结果存入 a0
    jalr x0, ra, 0           # 返回

# ==============================================================================
# multiply_signed — 32-bit 有符号乘法 (a0 × a1 → a0)
# ==============================================================================
# 算法: 取两操作数的绝对值 → 无符号乘法 → 根据符号恢复正负
# 破坏: t3 (临时存符号)
# ==============================================================================
multiply_signed:
    li   t0, 0               # t0 = 符号标志 (0=正, 1=负)

    # ---- 处理被乘数符号 ----
    bgez a0, ms_check_b      # a0 >= 0 → 跳过
    sub  a0, x0, a0          # a0 = -a0 (取绝对值)
    xori t0, t0, 1           # 翻转符号标志

ms_check_b:
    # ---- 处理乘数符号 ----
    bgez a1, ms_do_mul       # a1 >= 0 → 跳过
    sub  a1, x0, a1          # a1 = -a1 (取绝对值)
    xori t0, t0, 1           # 翻转符号标志

ms_do_mul:
    # ---- 保存返回地址 + 符号 ----
    addi sp, sp, -8
    sw   ra, 0(sp)
    sw   t0, 4(sp)

    # ---- 无符号乘法 ----
    jal  ra, multiply

    # ---- 恢复符号 + 返回地址 ----
    lw   t0, 4(sp)
    lw   ra, 0(sp)
    addi sp, sp, 8

    # ---- 若符号为负, 取补码 ----
    beqz t0, ms_done
    sub  a0, x0, a0          # a0 = -a0

ms_done:
    jalr x0, ra, 0

# ==============================================================================
# 自测试 (可选, 不会在正常加载时执行 — 需手动设置 PC 到 _start)
# ==============================================================================
# 测试用例:
#   3 × 5 = 15
#   0 × 100 = 0
#   -4 × 7 = -28
#   -3 × -6 = 18
#   0x10000 × 0x10000 = 0x100000000 → 低32位 = 0
# 结果存入 DMem 0x0000-0x0027
# ==============================================================================
_start:
    # 初始化栈指针 (复位后 sp=x2=0, 需指向 DMem 可用区域)
    li   sp, 0x0000FFC0       # sp = 64KB DMem 顶部附近 (64字节安全区域)

    # Test 1: 3 × 5 = 15 (无符号)
    li   a0, 3
    li   a1, 5
    jal  ra, multiply
    sw   a0, 0(x0)           # [0] = 15

    # Test 2: 0 × 100 = 0
    li   a0, 0
    li   a1, 100
    jal  ra, multiply
    sw   a0, 4(x0)           # [4] = 0

    # Test 3: 0xFFFF × 0x0001 = 0xFFFF
    li   a0, 0xFFFF
    li   a1, 1
    jal  ra, multiply
    sw   a0, 8(x0)           # [8] = 65535

    # Test 4: -4 × 7 = -28 (有符号)
    li   a0, -4
    li   a1, 7
    jal  ra, multiply_signed
    sw   a0, 12(x0)          # [12] = -28

    # Test 5: -3 × -6 = 18 (有符号)
    li   a0, -3
    li   a1, -6
    jal  ra, multiply_signed
    sw   a0, 16(x0)          # [16] = 18

    # Test 6: 100 × 200 = 20000
    li   a0, 100
    li   a1, 200
    jal  ra, multiply
    sw   a0, 20(x0)          # [20] = 20000

    # Test 7: 0x10000 × 0x10000 → 低32位 = 0, 高32位丢弃
    lui  a0, 0x1             # a0 = 0x10000 (65536)
    lui  a1, 0x1             # a1 = 0x10000
    jal  ra, multiply
    sw   a0, 24(x0)          # [24] = 0 (溢出, 低32位=0)

    # Test 8: 7 × (-4) = -28 (有符号, 控顺序)
    li   a0, 7
    li   a1, -4
    jal  ra, multiply_signed
    sw   a0, 28(x0)          # [28] = -28

# 测试完成 → 死循环
done:
    j    done
