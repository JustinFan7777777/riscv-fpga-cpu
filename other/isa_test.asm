# ==============================================================================
# isa_test.asm — ISA 扩展测试 (POPCNT / CLZ / CTZ)
# ==============================================================================
# 自定义 R-type 指令编码 (funct7=0000001, rs2=x0, rd=rs1=t0=x5):
#   POPCNT: funct7=0000001 funct3=001 rd=00101 rs1=00101 rs2=00000 → 0x0200B293
#   CLZ:    funct7=0000001 funct3=010 rd=00101 rs1=00101 rs2=00000 → 0x0200D293
#   CTZ:    funct7=0000001 funct3=011 rd=00101 rs1=00101 rs2=00000 → 0x0200F293
#
# 结果存 DMem 0x0000-0x003F, 通过 Debug 命令读取验证:
#   POPCNT 预期: [0]=0  [4]=32  [8]=1  [12]=1  [16]=16  [20]=16
#   CLZ    预期: [24]=32 [28]=0 [32]=0 [36]=31 [40]=16 [44]=8
#   CTZ    预期: [48]=32 [52]=0 [56]=0 [60]=31 [64]=8  [68]=4
#
# 编译: RARS → dump .text HexText isa_test.hex
# ==============================================================================

.text
.globl _start

_start:
    # ========================================================================
    # POPCNT — 统计 '1' 的个数
    # ========================================================================
    # Test 1: popcount(0) = 0
    li   t0, 0
    .word 0x0200B293               # POPCNT t0, t0
    sw   t0, 0(x0)

    # Test 2: popcount(0xFFFFFFFF) = 32
    li   t0, -1
    .word 0x0200B293
    sw   t0, 4(x0)

    # Test 3: popcount(1) = 1
    li   t0, 1
    .word 0x0200B293
    sw   t0, 8(x0)

    # Test 4: popcount(0x80000000) = 1
    lui  t0, 0x80000
    .word 0x0200B293
    sw   t0, 12(x0)

    # Test 5: popcount(0xAAAAAAAA) = 16
    lui  t0, 0xAAAAA
    addi t0, t0, 0x555            # 0xAAAAA555 ≈ 0xAAAAAAAA after shift
    slli t0, t0, 1
    addi t0, t0, 1                # t0 = 0xAAAAAAAB... no
    # 简化: 使用 0x33333333 → popcount = 16
    lui  t0, 0x33333
    addi t0, t0, 0x333            # t0 ≈ 0x33333333 (popcount=16)
    .word 0x0200B293
    sw   t0, 16(x0)

    # Test 6: popcount(0x00FF00FF) = 16
    lui  t0, 0x00FF0
    addi t0, t0, 0x0FF
    .word 0x0200B293
    sw   t0, 20(x0)

    # ========================================================================
    # CLZ — 统计前导零
    # ========================================================================
    # Test 7: clz(0) = 32
    li   t0, 0
    .word 0x0200D293               # CLZ t0, t0
    sw   t0, 24(x0)

    # Test 8: clz(0xFFFFFFFF) = 0
    li   t0, -1
    .word 0x0200D293
    sw   t0, 28(x0)

    # Test 9: clz(0x80000000) = 0
    lui  t0, 0x80000
    .word 0x0200D293
    sw   t0, 32(x0)

    # Test 10: clz(1) = 31
    li   t0, 1
    .word 0x0200D293
    sw   t0, 36(x0)

    # Test 11: clz(0x0000FFFF) = 16
    lui  t0, 0x00010
    addi t0, t0, -1               # t0 = 0x0000FFFF
    .word 0x0200D293
    sw   t0, 40(x0)

    # Test 12: clz(0x00FF0000) = 8
    lui  t0, 0x00FF0
    .word 0x0200D293
    sw   t0, 44(x0)

    # ========================================================================
    # CTZ — 统计尾部零
    # ========================================================================
    # Test 13: ctz(0) = 32
    li   t0, 0
    .word 0x0200F293               # CTZ t0, t0
    sw   t0, 48(x0)

    # Test 14: ctz(0xFFFFFFFF) = 0
    li   t0, -1
    .word 0x0200F293
    sw   t0, 52(x0)

    # Test 15: ctz(1) = 0
    li   t0, 1
    .word 0x0200F293
    sw   t0, 56(x0)

    # Test 16: ctz(0x80000000) = 31
    lui  t0, 0x80000
    .word 0x0200F293
    sw   t0, 60(x0)

    # Test 17: ctz(0x0000FF00) = 8
    li   t0, 0xFF
    slli t0, t0, 8                # t0 = 0x0000FF00
    .word 0x0200F293
    sw   t0, 64(x0)

    # Test 18: ctz(0x00000010) = 4
    li   t0, 0x10
    .word 0x0200F293
    sw   t0, 68(x0)

    # ========================================================================
    # 测试完成 — 死循环
    # ========================================================================
done:
    j    done
